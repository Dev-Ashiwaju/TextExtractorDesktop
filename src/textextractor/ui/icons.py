def svg_bytes(name: str, color: str, stroke: float = 2.0) -> QByteArray:
    body = _BODY[name].replace("{c}", color)
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
           f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')
    return QByteArray(svg.encode("utf-8"))


def pixmap(name: str, color: str, size: int = 18, stroke: float = 2.0, pad_right: int = 0) -> QPixmap:
    dpr = 2.0
    app = QGuiApplication.instance()
    if app is not None:
        screen = QGuiApplication.primaryScreen()
        if screen is not None:
            dpr = max(2.0, screen.devicePixelRatio())
    pm = QPixmap(int((size + pad_right) * dpr), int(size * dpr))
    pm.setDevicePixelRatio(dpr)
    pm.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pm)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    QSvgRenderer(svg_bytes(name, color, stroke)).render(painter, QRectF(0, 0, size, size))
    painter.end()
    return pm


def icon(name: str, color: str, disabled_color: str | None = None, size: int = 18, pad_right: int = 0) -> QIcon:
    ic = QIcon()
    ic.addPixmap(pixmap(name, color, size, pad_right=pad_right), QIcon.Mode.Normal)
    ic.addPixmap(pixmap(name, disabled_color or color, size, pad_right=pad_right), QIcon.Mode.Disabled)
    return ic
